def random_control(tr, spr, nrep=500, seed=11, uncond=False):
    """Control (i): same trades' count per NY day, same time-of-day window of the owning setup, same side, hold times permuted within
    (setup, era). Cost = same spread layer + swap. No stops in the control (the setups' own stops are part of the tested exit)."""
    t = ctx.t
    rng = np.random.default_rng(seed)
    tr = tr.reset_index(drop=True)
    cand = {}
    for s in tr.setup.unique():
        m = np.ones(ctx.n, bool)
        if s in WIN_TOD:
            m = (ctx.tod >= WIN_TOD[s][0]) & (ctx.tod < WIN_TOD[s][1])
        m &= t >= GLOBAL_START
        cand[s] = np.flatnonzero(m)
    lo = np.zeros(len(tr), np.int64)
    cnt = np.zeros(len(tr), np.int64)
    base = np.zeros(len(tr), np.int64)
    for s, idx in cand.items():
        k = np.flatnonzero(tr.setup.to_numpy() == s)
        cd = ctx.nyd[idx]
        lo[k] = np.searchsorted(cd, tr.day.to_numpy()[k], "left")
        cnt[k] = np.searchsorted(cd, tr.day.to_numpy()[k], "right") - lo[k]
    if uncond:      # ignore the trade's day: draw from the whole era (same n per setup and era)
        for s, idx in cand.items():
            b = int(np.searchsorted(idx, int(np.searchsorted(ctx.t, ERA_CUT))))
            k = np.flatnonzero(tr.setup.to_numpy() == s)
            e1 = tr.era.to_numpy()[k] == 1
            lo[k] = np.where(e1, 0, b)
            cnt[k] = np.where(e1, b, len(idx) - b)
    groups = [np.flatnonzero((tr.setup.to_numpy() == s) & (tr.era.to_numpy() == e)) for s in tr.setup.unique() for e in (1, 2)]
    groups = [g for g in groups if len(g)]
    hold = tr.hold_min.to_numpy()
    dr = tr.dir.to_numpy()
    st = tr.setup.to_numpy()
    out = np.zeros((nrep, 2))
    outn = np.zeros((nrep, 2))
    for r in range(nrep):
        e = np.zeros(len(tr), np.int64)
        for s, idx in cand.items():
            k = np.flatnonzero(st == s)
            e[k] = idx[lo[k] + np.minimum((rng.random(len(k)) * cnt[k]).astype(np.int64), cnt[k] - 1)]
        hp = hold.copy()
        for g in groups:
            hp[g] = hold[g][rng.permutation(len(g))]
        xi = np.searchsorted(t, t[e] + (hp * 60).astype("timedelta64[s]").astype("timedelta64[ns]"), "left")
        xi = np.minimum(xi, ctx.n - 1)
        fl = FLAT_FLAG[st] & (ctx.tod[e] < FLAT_TOD)
        xi = np.where(fl, np.minimum(xi, FLAT_IDX[e]), xi)
        xi = np.maximum(xi, e)
        long_ = dr > 0
        pts = np.where(long_, ctx.o[xi] - (ctx.o[e] + spr[e]), ctx.o[e] - (ctx.o[xi] + spr[xi]))
        nights = ctx.cumw[xi] - ctx.cumw[e]
        pts = pts + np.where(long_, nights * SWAP[0], nights * SWAP[1])
        er = ctx.era[e]
        for q in (1, 2):
            m = er == q
            out[r, q - 1] = pts[m].mean() if m.any() else np.nan
    return out


