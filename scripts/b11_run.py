def sens_rows(label, sigs, spr=spr_real, **kw):
    rows = []
    for name, en in ITEMS:
        d = run(ctx, sigs, spr, enabled=en, swap=SWAP, **kw)
        for q, lab in ((1, "E1"), (2, "E2")):
            sm = summarize(d[d.era == q], "net")
            rows.append({"variant": label, "item": name, "era": lab, "n": sm["n"], "mean": sm["mean"], "lo": sm["lo"], "hi": sm["hi"], "win": sm["win"], "pf": sm["pf"], "sum": sm["sum"]})
    return rows


